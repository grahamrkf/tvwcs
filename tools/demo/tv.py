import sys, os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from demo import *

restart("tv")
r = Demo("demo-tv-mode", note_x="736+(w-736-text_w)/2")
r.cap("TVWCS Quick Menu in TV mode\nAll apps in this demo are mockups", "title")
r.wait(3.5)
r.end("title")
r.cap("Nothing is open, so the Quick Menu stays on screen", "note")
r.wait(2.5)
r.cap("Open Streamly by its channel number", "note")
r.cap("Remote:  0  4")
r.typ("04", 0.5)
r.wait(0.3)
r.cap("Remote:  OK")
r.key("Return", 1.2)
r.end("key")
r.end("note")
r.wait(4)
r.cap("Remote:  Menu")
r.key("F2", 1.5)
r.cap("Open GameShelf on channel 12", "note")
r.cap("Remote:  1  2")
r.typ("12", 0.5)
r.wait(0.3)
r.cap("Remote:  OK")
r.key("Return", 1.2)
r.end("key")
r.end("note")
r.wait(4)
r.cap("Remote:  Menu")
r.key("F2", 1.5)
r.cap("Switch back to Streamly from the open apps", "note")
r.cap("Remote:  Up  Up")
r.key("Up", 0.6)
r.key("Up", 1.4)
r.cap("Remote:  OK")
r.key("Return", 1.2)
r.end("key")
r.end("note")
r.wait(4)
r.cap("Remote:  Menu")
r.key("F2", 1.5)
r.cap("Find RetroBox Console by searching its name", "note")
r.cap("Keyboard:  r e t r o")
r.typ("retro", 0.4)
r.wait(1.5)
r.cap("Remote:  OK")
r.key("Return", 1.2)
r.end("key")
r.end("note")
r.wait(4.5)
r.cap("Remote:  Menu")
r.key("F2", 1.2)
r.cap("All three apps, each on its own workspace", "note")
r.end("key")
r.wait(3.5)
r.cap("Remote:  Back")
r.key("Escape", 1.2)
r.end("key")
r.end("note")
r.wait(1.5)
r.play()
